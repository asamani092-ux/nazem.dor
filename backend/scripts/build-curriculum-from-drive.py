def row(level: str, week: int, day: str, educational: str) -> dict:
    edu = (educational or "").strip() or "-"
    return {
        "level": level,
        "week": week,
        "day": day,
        "educational": edu,
        "homework": "",
        "tarbawi": "",
    }


def emit(level: str, weeks: list[list[str]], days: list[str]) -> list[dict]:
    out: list[dict] = []
    for i, cells in enumerate(weeks, start=1):
        # إن كان صف واحد فقط (أسبوع كامل بنفس المحتوى)
        if len(cells) == 1:
            for d in days:
                out.append(row(level, i, d, cells[0]))
            continue
        for d, cell in zip(days, cells):
            if str(cell).strip():
                out.append(row(level, i, d, str(cell)))
    return out


